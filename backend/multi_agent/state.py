from typing import (
    TypedDict,
    Optional,
    Any,
    List,
    Dict
)


# =========================================================
# LANGGRAPH SHARED STATE
# =========================================================

class AgentState(
    TypedDict,
    total=False
):


    # =====================================================
    # USER INPUT
    # =====================================================

    question: str


    # =====================================================
    # AI PLANNER OUTPUT
    # =====================================================

    plan: List[str]


    # =====================================================
    # DETECTED BUSINESS INTENT
    # =====================================================

    intent: Optional[str]


    # =====================================================
    # WORKFLOW TRACKER
    # =====================================================

    current: str


    # =====================================================
    # DATA AGENT RESULT
    # =====================================================

    data: Optional[
        Dict[str, Any]
    ]


    # =====================================================
    # SALES INTELLIGENCE RESULT
    # =====================================================

    sales: Optional[
        Dict[str, Any]
    ]


    # =====================================================
    # FORECAST INTELLIGENCE RESULT
    # =====================================================

    forecast: Optional[
        Dict[str, Any]
    ]


    # =====================================================
    # INVENTORY INTELLIGENCE RESULT
    # =====================================================

    inventory: Optional[
        Dict[str, Any]
    ]


    # =====================================================
    # CUSTOMER INTELLIGENCE RESULT
    # =====================================================

    customer: Optional[
        Dict[str, Any]
    ]


    # =====================================================
    # BUSINESS RISK RESULT
    # =====================================================

    risk: Optional[
        Dict[str, Any]
    ]


    # =====================================================
    # DECISION ENGINE RESULT
    # =====================================================

    decision: Optional[
        Dict[str, Any]
    ]


    # =====================================================
    # REPORT GENERATOR RESULT
    # =====================================================

    report: Optional[
        Dict[str, Any]
    ]


    # =====================================================
    # EXECUTIVE DASHBOARD RESULT
    # =====================================================

    executive: Optional[
        Dict[str, Any]
    ]


    # =====================================================
    # AI RECOMMENDATIONS
    # =====================================================

    recommendations: Optional[
        Dict[str, Any]
    ]


    # =====================================================
    # LANGGRAPH MESSAGES
    # =====================================================

    messages: List[Any]


    # =====================================================
    # EXECUTION METADATA
    # =====================================================

    metadata: Optional[
        Dict[str, Any]
    ]


    # =====================================================
    # ERROR HANDLING
    # =====================================================

    error: Optional[str]


    # =====================================================
    # FINAL AI RESPONSE
    # =====================================================

    response: Optional[
        Dict[str, Any]
    ]

